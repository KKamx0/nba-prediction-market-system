"""edgebot command line.

edgebot init-db
edgebot ingest nba --season 2024-25 --season 2025-26
edgebot ingest schedule --season 2026-27
edgebot ingest injuries
edgebot ingest odds-history FILE --layout wide --source kaggle --home-col ...
edgebot snapshot markets [--hours 36]
edgebot snapshot odds
"""

from __future__ import annotations

import argparse
import logging
import os
import sys
from collections.abc import Callable, Sequence
from datetime import timedelta
from pathlib import Path

from edgebot.config import Settings, install_log_redaction
from edgebot.db import Store
from edgebot.timeutil import utc_now

log = logging.getLogger("edgebot")

Handler = Callable[[argparse.Namespace, Settings, Store], int]


def cmd_init_db(args: argparse.Namespace, settings: Settings, store: Store) -> int:
    print(f"database ready at {settings.db_path} (schema v{store.schema_version()})")
    return 0


def cmd_ingest_nba(args: argparse.Namespace, settings: Settings, store: Store) -> int:
    from edgebot.ingest.nba_stats import NbaStats, ingest_season

    stats = NbaStats(settings.cache_dir / "nba_api")
    for season in args.season:
        counts = ingest_season(store, stats, season, refresh=args.refresh)
        print(f"{season}: {counts['games']} games, {counts['player_games']} player lines")
    return 0


def cmd_ingest_schedule(args: argparse.Namespace, settings: Settings, store: Store) -> int:
    from edgebot.ingest.nba_stats import NbaStats, ingest_schedule

    n = ingest_schedule(store, NbaStats(settings.cache_dir / "nba_api"), args.season)
    print(f"{args.season}: {n} scheduled games")
    return 0


def cmd_ingest_injuries(args: argparse.Namespace, settings: Settings, store: Store) -> int:
    from edgebot.ingest.injuries import InjuryReports, ingest_new_reports

    n = ingest_new_reports(store, InjuryReports(listing_url=args.listing_url))
    print(f"{n} new injury report rows")
    return 0


def cmd_ingest_odds_history(args: argparse.Namespace, settings: Settings, store: Store) -> int:
    from edgebot.ingest.historical_odds import ColumnMap, load_file

    cmap = ColumnMap(
        date=args.date_col,
        home=args.home_col,
        away=args.away_col,
        home_odds=args.home_odds_col,
        away_odds=args.away_odds_col,
        odds_format=args.odds_format,
        date_format=args.date_format,
    )
    rep = load_file(
        args.file,
        layout=args.layout,
        source=args.source,
        cmap=cmap,
        season_start_year=args.season_start_year,
        max_reject_rate=args.max_reject_rate,
    )
    n = store.insert_odds_quotes(rep.rows)
    print(f"{n} closing lines imported, {sum(rep.rejected.values())} rejected {dict(rep.rejected)}")
    return 0


def cmd_snapshot_markets(args: argparse.Namespace, settings: Settings, store: Store) -> int:
    from edgebot.ingest.polymarket import PolymarketPublic, snapshot_to_store

    pm = PolymarketPublic()
    now = utc_now()
    upcoming = [
        m for m in pm.nba_moneylines() if now < m.start_utc <= now + timedelta(hours=args.hours)
    ]
    for ml in upcoming:
        snapshot_to_store(store, ml, pm.book(ml.market_slug))
    print(f"snapshotted {len(upcoming)} NBA moneyline books")
    return 0


def cmd_snapshot_odds(args: argparse.Namespace, settings: Settings, store: Store) -> int:
    from edgebot.ingest.odds_api import OddsApi

    api = OddsApi(settings.odds_api_key.get())
    n = store.insert_odds_quotes(api.nba_moneylines())
    print(f"{n} sportsbook quotes stored ({api.remaining} API credits left)")
    return 0


def cmd_backtest(args: argparse.Namespace, settings: Settings, store: Store) -> int:
    import json

    import pandas as pd

    from edgebot.model.backtest import (
        build_dataset,
        calibration_plot,
        report_markdown,
        score,
        select_model,
        walk_forward,
    )

    cache = settings.db_path.parent / "backtest_dataset.csv"
    if cache.exists() and not args.rebuild:
        df = pd.read_csv(cache, dtype={"game_id": str})
    else:
        df = build_dataset(store, progress=lambda d: print(f"\rbuilding features {d}", end=""))
        print()
        df.to_csv(cache, index=False)
    preds = walk_forward(df, [*args.validate, *args.test])
    if preds.empty:
        print("no predictions: check that the seasons have results and closing lines")
        return 1
    scores = score(preds)
    chosen = select_model(scores, args.validate)
    out = Path(args.out)
    test_preds = preds[preds["season"].isin(args.test)]
    calibration_plot(
        test_preds, ["market_raw", "market", chosen], out / "calibration.png", "Test seasons"
    )
    note = (
        "Sportsbook closing lines and NBA box scores only; no Polymarket data. "
        "Generated by `edgebot backtest`."
    )
    (out / "README.md").write_text(
        report_markdown(scores, chosen, args.validate, args.test, "calibration.png", note)
    )
    choice = settings.db_path.parent / "model_choice.json"
    choice.write_text(json.dumps({"model": chosen, "validate": args.validate, "test": args.test}))
    print(f"selected {chosen}; report written to {out / 'README.md'}")
    return 0


def cmd_train(args: argparse.Namespace, settings: Settings, store: Store) -> int:
    import json

    import pandas as pd

    from edgebot.model.game_model import default_models, save_model

    cache = settings.db_path.parent / "backtest_dataset.csv"
    if not cache.exists():
        print("run `edgebot backtest` first; it builds the training set")
        return 1
    df = pd.read_csv(cache, dtype={"game_id": str})
    df = df[df["market_logit"].notna()].sort_values(["game_date", "game_id"])
    choice = settings.db_path.parent / "model_choice.json"
    name = args.model or json.loads(choice.read_text())["model"]
    model = default_models()[name]().fit(df, df["y"].to_numpy())
    path = Path("models") / "game_model.pkl"
    save_model(model, path)
    print(f"trained {name} on {len(df)} games -> {path}")
    return 0


def cmd_report(args: argparse.Namespace, settings: Settings, store: Store) -> int:
    from edgebot import report

    s = report.compute(store, mode=args.mode, starting_bankroll=settings.paper_bankroll)
    text = report.to_text(s)
    print(text)
    if args.export:
        out = Path(args.export)
        plot = out.parent / "results_calibration.png"
        has_plot = report.calibration_png(store, plot)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(report.to_markdown(s, plot.name if has_plot else None))
        print(f"exported {out}")
    if args.send:
        if not settings.discord_webhook_url:
            print("DISCORD_WEBHOOK_URL is not set; nothing sent")
            return 1
        report.send_discord(settings.discord_webhook_url.get(), text)
        print("sent to Discord")
    return 0


def cmd_doctor(args: argparse.Namespace, settings: Settings, store: Store) -> int:
    import httpx

    from edgebot.doctor import data_checks, network_checks, render

    checks = data_checks(store, settings)
    if args.network:
        with httpx.Client(timeout=15, follow_redirects=True) as c:
            checks += network_checks(lambda url: c.get(url).status_code)
    print(render(checks))
    failed = [c for c in checks if c.level == "fail"]
    print(f"\n{len(failed)} blocking problem(s)" if failed else "\nready for paper mode")
    return 1 if failed else 0


KILL_FILE = Path("run") / "KILL"


def _risk_engine(settings: Settings, store: Store):
    from edgebot.trading.risk import RiskEngine, RiskLimits
    from edgebot.trading.state import load_risk_state

    return RiskEngine(RiskLimits(), load_risk_state(store, settings.paper_bankroll), KILL_FILE)


def build_runner(settings: Settings, store: Store, *, executor=None, risk=None):  # noqa: ANN001
    """Wire the trading loop. Paper by default; trading/live.py passes a LiveExecutor."""
    import json

    from edgebot.ingest.injuries import InjuryReports, ingest_new_reports
    from edgebot.ingest.nba_stats import NbaStats, ingest_season
    from edgebot.ingest.odds_api import OddsApi
    from edgebot.ingest.polymarket import PolymarketPublic
    from edgebot.model.game_model import load_model
    from edgebot.runner import Runner
    from edgebot.timeutil import season_for_date
    from edgebot.trading.executor import PaperExecutor

    model_path = Path("models") / "game_model.pkl"
    if not model_path.exists():
        raise SystemExit("no trained model: run `edgebot backtest ...` then `edgebot train`")
    choice = settings.db_path.parent / "model_choice.json"
    model_name = json.loads(choice.read_text())["model"] if choice.exists() else "unknown"

    pm = PolymarketPublic()
    odds = None
    if settings.odds_api_key:
        api = OddsApi(settings.odds_api_key.get())
        odds = lambda: store.insert_odds_quotes(api.nba_moneylines())  # noqa: E731
    stats = NbaStats(settings.cache_dir / "nba_api")
    reports = InjuryReports()
    daily_report = None
    if settings.discord_webhook_url:
        from edgebot import report

        def daily_report() -> None:
            s = report.compute(store, starting_bankroll=settings.paper_bankroll)
            report.send_discord(settings.discord_webhook_url.get(), report.to_text(s))

    news = None
    if settings.anthropic_api_key:
        from edgebot.ingest.http import JsonClient
        from edgebot.news import DEFAULT_FEEDS, NewsExtractor, ingest_news

        extractor = NewsExtractor()
        feed_client = JsonClient("https://", rate_per_s=0.5)
        feeds = [f for f in os.environ.get("NEWS_FEEDS", ",".join(DEFAULT_FEEDS)).split(",") if f]

        def news(teams: set[str], rosters: dict[str, set[str]]) -> int:
            return ingest_news(
                store, extractor, feed_client.get_bytes,
                teams_tonight=teams, rosters=rosters, feeds=feeds,
            )  # fmt: skip

    return Runner(
        store=store,
        model=load_model(model_path),
        model_name=model_name,
        executor=executor or PaperExecutor(store, pm.book, theta=0.095),
        risk=risk or _risk_engine(settings, store),
        polymarket=pm,
        injuries=lambda: ingest_new_reports(store, reports),
        odds=odds,
        results=lambda: ingest_season(
            store, stats, season_for_date(utc_now().date()), refresh=True
        ),
        daily_report=daily_report,
        news=news,
    )


def cmd_run(args: argparse.Namespace, settings: Settings, store: Store) -> int:
    if args.live:
        from edgebot.trading.live import run_live

        return run_live(args, settings, store)
    runner = build_runner(settings, store)
    print(f"paper mode: bankroll ${runner.risk.state.bankroll:,.2f}; `edgebot kill` to stop")
    if args.once:
        r = runner.cycle()
        print(
            f"{r.snapshots} snapshots, {r.evaluated} evaluated, {r.bets} bets, {r.settled} settled"
        )
        return 0
    runner.run(args.interval)
    return 0


def cmd_kill(args: argparse.Namespace, settings: Settings, store: Store) -> int:
    from edgebot.trading.state import log_risk_event

    if args.clear:
        KILL_FILE.unlink(missing_ok=True)
        log_risk_event(store, "kill_switch_cleared", "manual")
        print("kill switch cleared")
        return 0
    KILL_FILE.parent.mkdir(parents=True, exist_ok=True)
    KILL_FILE.write_text(f"engaged {utc_now().isoformat()}\n")
    log_risk_event(store, "kill_switch", "engaged from CLI")
    print(f"kill switch engaged ({KILL_FILE}); the loop cancels open orders and stops")
    return 0


def cmd_risk(args: argparse.Namespace, settings: Settings, store: Store) -> int:
    from edgebot.trading.state import log_risk_event, save_risk_state

    eng = _risk_engine(settings, store)
    s = eng.state
    if args.action == "reset":
        if not s.shutdown and s.halted_until is None:
            print("nothing to reset")
            return 0
        eng.manual_reset(confirm=args.confirm)  # raises without --confirm
        save_risk_state(store, s)
        log_risk_event(store, "manual_reset", f"bankroll {s.bankroll:.2f}")
        print("risk breakers reset; drawdown is now measured from the current bankroll")
        return 0
    print(
        f"bankroll ${s.bankroll:,.2f} | peak ${s.peak:,.2f} | drawdown {eng.drawdown():.1%} | "
        f"today {-eng.daily_loss():.1%} | open exposure ${s.open_exposure:,.2f}\n"
        f"halted until: {s.halted_until or '-'} | shutdown: {s.shutdown_reason or 'no'} | "
        f"kill switch: {'ENGAGED' if eng.killed() else 'off'}"
    )
    return 0


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="edgebot", description=__doc__.split("\n\n")[0])
    p.add_argument("-v", "--verbose", action="store_true")
    sub = p.add_subparsers(dest="command", required=True)

    sub.add_parser("init-db", help="create or migrate the database").set_defaults(fn=cmd_init_db)

    ingest = sub.add_parser("ingest", help="load data into the database")
    isub = ingest.add_subparsers(dest="source", required=True)

    nba = isub.add_parser("nba", help="box scores and player minutes via nba_api")
    nba.add_argument("--season", action="append", required=True, help="e.g. 2025-26 (repeatable)")
    nba.add_argument("--refresh", action="store_true", help="ignore the local cache")
    nba.set_defaults(fn=cmd_ingest_nba)

    sched = isub.add_parser("schedule", help="season schedule with tip times")
    sched.add_argument("--season", required=True)
    sched.set_defaults(fn=cmd_ingest_schedule)

    inj = isub.add_parser("injuries", help="new official injury reports")
    from edgebot.ingest.injuries import LISTING_URL

    inj.add_argument("--listing-url", default=LISTING_URL)
    inj.set_defaults(fn=cmd_ingest_injuries)

    oh = isub.add_parser("odds-history", help="import free archived closing lines (CSV)")
    oh.add_argument("file")
    oh.add_argument("--layout", choices=["wide", "sbr"], required=True)
    oh.add_argument("--source", required=True, help="short name stored with each row")
    oh.add_argument("--season-start-year", type=int, help="sbr layout: e.g. 2019 for 2019-20")
    oh.add_argument("--date-col", default="date")
    oh.add_argument("--home-col", default="home")
    oh.add_argument("--away-col", default="away")
    oh.add_argument("--home-odds-col", default="home_ml")
    oh.add_argument("--away-odds-col", default="away_ml")
    oh.add_argument("--odds-format", choices=["american", "decimal"], default="american")
    oh.add_argument("--date-format", help="strptime pattern if dates aren't ISO")
    oh.add_argument("--max-reject-rate", type=float, default=0.05)
    oh.set_defaults(fn=cmd_ingest_odds_history)

    snap = sub.add_parser("snapshot", help="capture live prices")
    ssub = snap.add_subparsers(dest="what", required=True)
    sm = ssub.add_parser("markets", help="Polymarket US NBA moneyline order books")
    sm.add_argument("--hours", type=float, default=36, help="only games tipping within N hours")
    sm.set_defaults(fn=cmd_snapshot_markets)
    ssub.add_parser("odds", help="sportsbook moneylines (The Odds API)").set_defaults(
        fn=cmd_snapshot_odds
    )
    bt = sub.add_parser("backtest", help="walk-forward backtest vs the market-only baseline")
    bt.add_argument(
        "--validate", action="append", required=True, help="season used to choose a model"
    )
    bt.add_argument(
        "--test", action="append", required=True, help="season reported, never tuned on"
    )
    bt.add_argument("--out", default="docs/backtest")
    bt.add_argument("--rebuild", action="store_true", help="recompute features")
    bt.set_defaults(fn=cmd_backtest)

    tr = sub.add_parser("train", help="fit the selected model on all data for live use")
    tr.add_argument("--model", help="override the backtest's choice")
    tr.set_defaults(fn=cmd_train)

    run = sub.add_parser("run", help="trading loop (paper by default)")
    run.add_argument("--once", action="store_true", help="run a single cycle and exit")
    run.add_argument("--interval", type=float, default=300, help="seconds between cycles")
    run.add_argument("--live", action="store_true", help="live trading (gated; see README)")
    run.add_argument("--confirm-live", action="store_true", help="required with --live")
    run.set_defaults(fn=cmd_run)

    doc = sub.add_parser("doctor", help="check data, model, keys, and connectivity")
    doc.add_argument("--network", action="store_true", help="also probe the data sources")
    doc.set_defaults(fn=cmd_doctor)

    rep = sub.add_parser("report", help="P&L, CLV, calibration vs market, drawdown")
    rep.add_argument("--mode", choices=["paper", "live"], default="paper")
    rep.add_argument("--export", help="write sanitized markdown, e.g. docs/results.md")
    rep.add_argument("--send", action="store_true", help="post to DISCORD_WEBHOOK_URL")
    rep.set_defaults(fn=cmd_report)

    kill = sub.add_parser("kill", help="engage the kill switch (cancel orders, stop the loop)")
    kill.add_argument("--clear", action="store_true", help="disengage it")
    kill.set_defaults(fn=cmd_kill)

    risk = sub.add_parser("risk", help="risk status, or reset a halt or shutdown")
    risk.add_argument("action", choices=["status", "reset"])
    risk.add_argument("--confirm", action="store_true", help="required for reset")
    risk.set_defaults(fn=cmd_risk)
    return p


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    settings = Settings.from_env()
    logging.basicConfig(
        level=logging.DEBUG if args.verbose else settings.log_level,
        format="%(asctime)s %(levelname)s %(name)s: %(message)s",
    )
    # httpx logs full request URLs at INFO, and some APIs take keys in the query
    # string. Keep those lines out of the logs entirely; redaction is the backstop.
    logging.getLogger("httpx").setLevel(logging.WARNING)
    logging.getLogger("httpcore").setLevel(logging.WARNING)
    install_log_redaction(settings)
    store = Store(settings.db_path)
    try:
        return args.fn(args, settings, store)
    finally:
        store.close()


if __name__ == "__main__":
    sys.exit(main())
